<?php
session_start();
require 'fpdf.php';
include 'DonRegConnection.php';
header('Content-Type: application/pdf');

//User must be logged in
if (!isset($_SESSION['user_id'])) {
    die('Access denied');
}
$donor_id = (int)$_SESSION['user_id'];

//Validate id parameter
$donation_id = isset($_GET['id']) ? (int)$_GET['id'] : 0;
if ($donation_id <= 0) {
    die('Invalid donation id');
}

//Ensuring donation belongs to this donor
//REMOVED d.status from query
$donStmt = $object->prepare("
    SELECT d.donation_id, d.total_items, d.donation_date, u.username
    FROM donations d
    JOIN users u ON d.donor_id = u.user_id
    WHERE d.donation_id = ? AND d.donor_id = ?
    LIMIT 1
");
$donStmt->bind_param("ii", $donation_id, $donor_id);
$donStmt->execute();
$don = $donStmt->get_result()->fetch_assoc();

if (!$don) {
    die('Donation not found or access denied');
}

//Fetching items
$itemStmt = $object->prepare("
    SELECT item_name, quantity, description, itemStatus
    FROM donation_items
    WHERE donation_id = ?
    ORDER BY item_id ASC
");
$itemStmt->bind_param("i", $donation_id);
$itemStmt->execute();
$itemsRes = $itemStmt->get_result();

//PDF
$pdf = new FPDF();
$pdf->AddPage();
$pdf->SetFont('Arial','B',16);
$pdf->Cell(0,10,'Donation Report',0,1,'C');
$pdf->Ln(4);

//Username
$pdf->SetFont('Arial','B',12);
$pdf->Cell(0,7,'Username: ' . $don['username'], 0, 1);
$pdf->Ln(5);

//Donation header
$pdf->SetFont('Arial','',12);
$pdf->Cell(0,7,'Donation Number: ' . $don['donation_id'], 0, 1);
$pdf->Cell(0,7,'Date: ' . date('F j, Y', strtotime($don['donation_date'])), 0, 1);
$pdf->Ln(6);

//--- Table Header ---
$pdf->SetFont('Arial','B',11);
$pdf->Cell(60,8,'Item Name',1,0,'C');
$pdf->Cell(25,8,'Qty',1,0,'C');
$pdf->Cell(35,8,'Status',1,0,'C');
$pdf->Cell(70,8,'Description',1,1,'C');

//--- Table Rows ---
$pdf->SetFont('Arial','',11);

while ($it = $itemsRes->fetch_assoc()) {

    //Wrap item name
    $itemName = wordwrap($it['item_name'], 25, "\n");

    //Wrap description
    $desc = $it['description'] ? wordwrap($it['description'], 40, "\n") : '-';

    //Calculate row height (max line count between itemName & description)
    $lineCount = max(
        substr_count($itemName, "\n") + 1,
        substr_count($desc, "\n") + 1
    );
    $rowHeight = 6 * $lineCount;

    //Draw Cells
    $x = $pdf->GetX();
    $y = $pdf->GetY();

    //Item Name
    $pdf->MultiCell(60,6,$itemName,1,'L');
    $pdf->SetXY($x + 60, $y);

    //Quantity
    $pdf->MultiCell(25,6,(int)$it['quantity'],1,'C');
    $pdf->SetXY($x + 85, $y);

    //Status
    $pdf->MultiCell(35,6,$it['itemStatus'],1,'C');
    $pdf->SetXY($x + 120, $y);

    //Description
    $pdf->MultiCell(70,6,$desc,1,'L');
}

$pdf->Ln(6);
$pdf->SetFont('Arial','I',9);
$pdf->Cell(0,6,'Generated by DIMS',0,1,'R');

$pdf->Output('I','donation_'.$donation_id.'.pdf');
exit;
?>